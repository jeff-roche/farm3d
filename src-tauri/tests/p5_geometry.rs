/// The XY extents of extrusion moves on the layers between `z_low` and
/// `z_high`, split into objects left and right of `x_split`.
fn extrusion_extents(gcode: &str, z_low: f64, z_high: f64, x_split: f64) -> [BoundsMm; 2] {
    let mut z = 0.0;
    let mut position = [0.0f64; 2];
    let mut extents: [Option<BoundsMm>; 2] = [None, None];
    for line in gcode.lines() {
        let line = line.split(';').next().unwrap_or("").trim();
        let mut words = line.split_whitespace();
        if !matches!(words.next(), Some("G1" | "G0")) {
            continue;
        }
        let mut extrudes = false;
        for word in words {
            let (axis, value) = word.split_at(1);
            let Ok(value) = value.parse::<f64>() else {
                continue;
            };
            match axis {
                "X" => position[0] = value,
                "Y" => position[1] = value,
                "Z" => z = value,
                "E" => extrudes = value > 0.0,
                _ => {}
            }
        }
        if extrudes && (z_low..=z_high).contains(&z) {
            let side = usize::from(position[0] >= x_split);
            let point = [position[0], position[1], z];
            match &mut extents[side] {
                Some(bounds) => {
                    let ranges = bounds.min.iter_mut().zip(bounds.max.iter_mut());
                    for ((min, max), value) in ranges.zip(point) {
                        *min = min.min(value);
                        *max = max.max(value);
                    }
                }
                none => {
                    *none = Some(BoundsMm {
                        min: point,
                        max: point,
                    })
                }
            }
        }
    }
    extents.map(|bounds| bounds.expect("both objects are extruded on the checked layers"))
}

#[test]
#[ignore = "needs a real OrcaSlicer: set FARM3D_ORCA (just test-orca)"]
fn real_orca_places_a_written_plate_exactly() {
    use farm3d_lib::slicing::presets::{
        default_filament, default_process, PresetIndex, PresetKind,
    };
    use farm3d_lib::slicing::repository::SlicerRuntimeConfig;
    use farm3d_lib::slicing::runtime::{orca_environment, resolve_runtime, DiscoveryEnv};
    use farm3d_lib::spools::MaterialFamily;

    let engine = std::env::var_os("FARM3D_ORCA")
        .map(PathBuf::from)
        .expect("FARM3D_ORCA must name an OrcaSlicer engine; run through `just test-orca`");
    let presets = std::env::var_os("FARM3D_ORCA_PRESETS").map(PathBuf::from);
    let cache = tempfile::tempdir().unwrap();
    let runtime = resolve_runtime(
        &SlicerRuntimeConfig {
            revision: 1,
            engine_path: Some(engine.to_str().unwrap().to_string()),
            preset_source_path: presets.map(|path| path.to_str().unwrap().to_string()),
            updated_at: None,
        },
        &DiscoveryEnv {
            home: None,
            path_var: None,
            probe_timeout: std::time::Duration::from_secs(20),
        },
        cache.path(),
    );
    let engine = runtime.engine.expect("an accepted engine");
    let source = runtime.preset_source.expect("a readable preset source");
    let index = PresetIndex::build(
        &source.profiles_dir,
        &source.version.to_string(),
        &CancelFlag::never(),
    )
    .unwrap();
    let machine = "Elegoo Centauri Carbon 0.4 nozzle";
    let process = default_process(&index.offered(PresetKind::Process, machine)).unwrap();
    let filament = default_filament(
        &index.offered(PresetKind::Filament, machine),
        &[MaterialFamily::Pla],
    )
    .unwrap();

    let work = tempfile::tempdir().unwrap();
    let input = work.path().join("input");
    let out = work.path().join("out");
    let datadir = work.path().join("datadir");
    for dir in [&input, &out, &datadir] {
        fs::create_dir_all(dir).unwrap();
    }
    for (kind, name, file) in [
        (PresetKind::Machine, machine, "machine.json"),
        (PresetKind::Process, process.as_str(), "process.json"),
        (PresetKind::Filament, filament.as_str(), "filament.json"),
    ] {
        let flat = index.flatten(kind, name).unwrap();
        fs::write(input.join(file), serde_json::to_vec_pretty(&flat).unwrap()).unwrap();
    }
    // Gate C: 20 mm cubes.
    let plate = write_plate_3mf(&two_cube_plate(2.0), &plate_source()).unwrap();
    fs::write(input.join("plate.3mf"), plate).unwrap();

    let status = std::process::Command::new(&engine.path)
        .current_dir(work.path())
        .env_clear()
        .envs(orca_environment())
        .arg("--datadir")
        .arg(&datadir)
        .arg("--outputdir")
        .arg(&out)
        .arg("--load-settings")
        .arg(format!(
            "{};{}",
            input.join("machine.json").display(),
            input.join("process.json").display()
        ))
        .arg("--load-filaments")
        .arg(input.join("filament.json"))
        .args(["--arrange", "0", "--orient", "0", "--slice", "1"])
        .arg(input.join("plate.3mf"))
        .status()
        .unwrap();
    assert!(status.success(), "OrcaSlicer exited with {status}");
    let gcode = fs::read_to_string(out.join("plate_1.gcode")).unwrap();

    // Around mid-height (Z 10 of 20), perimeters sit about 0.21 mm inside
    // the footprint (Gate C).
    let [a, b] = extrusion_extents(&gcode, 9.5, 10.5, 100.0);
    eprintln!("A: {a:?}\nB: {b:?}");
    let diagonal = 20.0 * std::f64::consts::SQRT_2;
    let expected_a = BoundsMm {
        min: [40.0, 40.0, 0.0],
        max: [60.0, 60.0, 0.0],
    };
    let expected_b = BoundsMm {
        min: [150.0 - diagonal / 2.0, 120.0, 0.0],
        max: [150.0 + diagonal / 2.0, 120.0 + diagonal, 0.0],
    };
    for (actual, expected, what) in [(a, expected_a, "A"), (b, expected_b, "B")] {
        for axis in 0..2 {
            assert!(
                (actual.min[axis] - expected.min[axis]).abs() < 0.6
                    && (actual.max[axis] - expected.max[axis]).abs() < 0.6,
                "{what}: {actual:?} vs {expected:?}"
            );
        }
    }
}
