#[test]
fn the_golden_plate_reads_back_through_the_p4_readers() {
    let path = slicing_fixtures().join(PLATE);
    let detected = formats::detect(&path).unwrap();
    assert_eq!(detected.format, ModelFormat::ThreeMf);
    let outcome = formats::inspect(&path, &detected, &CancelFlag::never()).unwrap();
    assert!(outcome.warnings.is_empty(), "{:?}", outcome.warnings);
    let Inspection::ThreeMf(model) = outcome.inspection else {
        panic!("not a 3MF");
    };
    assert_eq!(model.object_count, 1);
    assert_eq!(model.build_item_count, 2);
    assert_eq!(model.triangle_count, 24);
    assert!(model.plates.is_empty() && model.unsupported.is_empty());
    let half_diagonal = 10.0 * std::f64::consts::FRAC_1_SQRT_2;
    assert_bounds_near(
        &model.bounds_mm,
        &BoundsMm {
            min: [40.0, 40.0, 0.0],
            max: [150.0 + half_diagonal, 120.0 + 2.0 * half_diagonal, 10.0],
        },
        1e-5,
        PLATE,
    );

    // The items carry the composed transforms (to 6 decimal places).
    let source = plate_source();
    let read_back = load(&path, ModelFormat::ThreeMf).unwrap();
    let plate = two_cube_plate(1.0);
    for (item, instance) in read_back
        .geometry()
        .build_items
        .iter()
        .zip(&plate.instances)
    {
        let expected = compose_transform(&instance.transform, &source.mesh(1).unwrap().positions);
        for (a, b) in item.transform.iter().zip(&expected) {
            assert!(
                (a - b).abs() <= 5e-7,
                "{:?} != {expected:?}",
                item.transform
            );
        }
    }
    assert_eq!(read_back.mesh(1), source.mesh(1));
}

