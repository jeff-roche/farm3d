fn load(path: &Path, format: ModelFormat) -> Result<LoadedRevision, formats::InspectError> {
    load_revision(File::open(path).unwrap(), format, &CancelFlag::never())
}

fn header_word(buffer: &[u8], at: usize) -> u32 {
    u32::from_le_bytes(buffer[at..at + 4].try_into().unwrap())
}

fn assert_bounds_near(actual: &BoundsMm, expected: &BoundsMm, tolerance: f64, what: &str) {
    for axis in 0..3 {
        assert!(
            (actual.min[axis] - expected.min[axis]).abs() <= tolerance
                && (actual.max[axis] - expected.max[axis]).abs() <= tolerance,
            "{what}: {actual:?} != {expected:?}"
        );
    }
}

