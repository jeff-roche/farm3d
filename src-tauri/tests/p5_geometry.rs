/// `transform-vectors.json`: shared with the frontend's D5 implementation.
#[derive(Serialize, Deserialize, Debug, PartialEq)]
#[serde(rename_all = "camelCase")]
struct TransformVectors {
    description: String,
    tolerance: f64,
    positions: Vec<[f32; 3]>,
    cases: Vec<TransformCase>,
}

#[derive(Serialize, Deserialize, Debug, PartialEq)]
#[serde(rename_all = "camelCase")]
struct TransformCase {
    name: String,
    transform: InstanceTransform,
    matrix: [f64; 12],
    world_bounds_mm: BoundsMm,
}

fn vector_inputs() -> (Vec<[f32; 3]>, Vec<(&'static str, InstanceTransform)>) {
    // A lopsided octahedron: its bounding-box corners aren't vertices, so a
    // box-based Z drop would differ from the vertex-based one.
    let positions = vec![
        [10.0, 0.0, 5.0],
        [-10.0, 0.0, 5.0],
        [0.0, 6.0, 5.0],
        [0.0, -6.0, 5.0],
        [0.0, 0.0, 15.0],
        [0.0, 0.0, -3.0],
        [4.0, 2.0, 9.0],
    ];
    let case = |translate: [f64; 2], rotate: [f64; 3], scale: [f64; 3]| InstanceTransform {
        translate_mm: translate,
        rotate_deg: rotate,
        scale,
    };
    let cases = vec![
        ("identity", case([0.0; 2], [0.0; 3], [1.0; 3])),
        ("rotateX90", case([0.0; 2], [90.0, 0.0, 0.0], [1.0; 3])),
        ("rotateY90", case([0.0; 2], [0.0, 90.0, 0.0], [1.0; 3])),
        ("rotateZ90", case([0.0; 2], [0.0, 0.0, 90.0], [1.0; 3])),
        ("rotateX30", case([0.0; 2], [30.0, 0.0, 0.0], [1.0; 3])),
        ("nonUniformScale", case([0.0; 2], [0.0; 3], [2.0, 0.5, 3.0])),
        (
            "combined",
            case([100.0, 50.0], [30.0, 45.0, 60.0], [1.5, 1.0, 0.75]),
        ),
        (
            "rotateZ45Translated",
            case([150.0, 120.0], [0.0, 0.0, 45.0], [1.0; 3]),
        ),
    ];
    (positions, cases)
}

fn computed_vectors() -> TransformVectors {
    let (positions, cases) = vector_inputs();
    let cases = cases
        .into_iter()
        .map(|(name, transform)| {
            let matrix = compose_transform(&transform, &positions);
            TransformCase {
                name: name.to_string(),
                world_bounds_mm: transformed_bounds(&matrix, &positions).unwrap(),
                transform,
                matrix,
            }
        })
        .collect();
    TransformVectors {
        description: "D5 instance transforms. The local mesh is scaled, rotated about X, then \
            Y, then Z (extrinsic, rad = deg * (PI / 180)), and translated by translateMm on \
            XY. matrix is the 3MF transform attribute order m00 m01 m02 m10 m11 m12 m20 m21 \
            m22 m30 m31 m32: a local point maps to x' = x*m[0] + y*m[3] + z*m[6] + m[9], \
            y' = x*m[1] + y*m[4] + z*m[7] + m[10], z' = x*m[2] + y*m[5] + z*m[8] + m[11]. \
            m[11] = -min over the vertices of ((x*m[2] + y*m[5]) + z*m[8]), so the lowest \
            vertex lands exactly on Z = 0. worldBoundsMm is over the placed vertices. \
            Compare numbers within tolerance."
            .to_string(),
        tolerance: 1e-9,
        positions,
        cases,
    }
}

#[test]
fn transform_vectors_match_the_d5_composition() {
    let text = fs::read_to_string(slicing_fixtures().join(VECTORS)).unwrap();
    let committed: TransformVectors = serde_json::from_str(&text).unwrap();
    let computed = computed_vectors();
    assert_eq!(committed.positions, computed.positions);
    assert_eq!(committed.cases.len(), computed.cases.len());
    let tolerance = committed.tolerance;
    assert_eq!(tolerance, 1e-9);
    for (committed, computed) in committed.cases.iter().zip(&computed.cases) {
        assert_eq!(committed.name, computed.name);
        assert_eq!(
            committed.transform, computed.transform,
            "{}",
            committed.name
        );
        for (index, (a, b)) in committed.matrix.iter().zip(&computed.matrix).enumerate() {
            assert!(
                (a - b).abs() <= tolerance,
                "{} m[{index}]: {a} != {b}",
                committed.name
            );
        }
        assert_bounds_near(
            &committed.world_bounds_mm,
            &computed.world_bounds_mm,
            tolerance,
            &committed.name,
        );
        assert_eq!(computed.world_bounds_mm.min[2], 0.0, "{}", committed.name);
        assert!(
            (committed.transform.translate_mm[0] - committed.matrix[9]).abs() <= tolerance
                && (committed.transform.translate_mm[1] - committed.matrix[10]).abs() <= tolerance
        );
    }

    // Spot checks independent of the implementation.
    let by_name = |name: &str| {
        computed
            .cases
            .iter()
            .find(|case| case.name == name)
            .unwrap()
    };
    // Identity: the apex at z = -3 drops the mesh by 3.
    assert_bounds_near(
        &by_name("identity").world_bounds_mm,
        &BoundsMm {
            min: [-10.0, -6.0, 0.0],
            max: [10.0, 6.0, 18.0],
        },
        1e-9,
        "identity",
    );
    // About X by 90°: y' = -z and z' = y, so z spans -6..6, dropped by 6.
    assert_bounds_near(
        &by_name("rotateX90").world_bounds_mm,
        &BoundsMm {
            min: [-10.0, -15.0, 0.0],
            max: [10.0, 3.0, 12.0],
        },
        1e-9,
        "rotateX90",
    );
    // Non-uniform scale: z × 3 spans -9..45.
    assert_bounds_near(
        &by_name("nonUniformScale").world_bounds_mm,
        &BoundsMm {
            min: [-20.0, -3.0, 0.0],
            max: [20.0, 3.0, 54.0],
        },
        1e-9,
        "nonUniformScale",
    );
    let placed = transform_point(&by_name("rotateZ45Translated").matrix, [10.0, 0.0, 0.0]);
    let half = 10.0 * std::f64::consts::FRAC_1_SQRT_2;
    assert!((placed[0] - (150.0 + half)).abs() < 1e-9 && (placed[1] - (120.0 + half)).abs() < 1e-9);
}

