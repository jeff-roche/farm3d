#[test]
fn every_model_fixture_has_geometry_and_a_mesh_buffer_or_is_rejected_as_before() {
    let dir = library_fixtures();
    let mut names: Vec<String> = fs::read_dir(&dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".stl") || name.ends_with(".3mf"))
        .collect();
    names.sort();
    assert!(names.len() >= 14, "{names:?}");

    let mut loaded = Vec::new();
    for name in &names {
        let path = dir.join(name);
        let oracle: serde_json::Value =
            serde_json::from_slice(&fs::read(dir.join(format!("{name}.expected.json"))).unwrap())
                .unwrap();
        let detected = formats::detect(&path);
        if let Some(code) = oracle.get("error").and_then(|code| code.as_str()) {
            let error = match detected {
                Err(error) => error,
                Ok(detected) => {
                    load(&path, detected.format).expect_err(&format!("{name} should be rejected"))
                }
            };
            assert_eq!(error.code(), code, "{name}: {error:?}");
            continue;
        }

        let detected = detected.unwrap();
        let inspection = formats::inspect(&path, &detected, &CancelFlag::never())
            .unwrap()
            .inspection;
        let revision =
            load(&path, detected.format).unwrap_or_else(|error| panic!("{name}: {error:?}"));
        let geometry = revision.geometry();

        // Every object's buffer decodes to its mesh's counts.
        for object in &geometry.objects {
            let mesh = revision.mesh(object.object_key).unwrap();
            let buffer = revision.mesh_buffer(object.object_key).unwrap();
            assert_eq!(buffer[..4], MESH_MAGIC, "{name}");
            assert_eq!(header_word(&buffer, 4), MESH_FORMAT_VERSION, "{name}");
            assert_eq!(header_word(&buffer, 8) as usize, mesh.positions.len());
            assert_eq!(header_word(&buffer, 12) as usize, mesh.triangles.len() * 3);
            assert_eq!(
                buffer.len(),
                16 + mesh.positions.len() * 12 + mesh.triangles.len() * 12,
                "{name}"
            );
            assert_eq!(object.triangle_count as usize, mesh.triangles.len());
            assert!(!object.lay_flat_faces.is_empty(), "{name}");
            assert!(object.lay_flat_faces.len() <= 8, "{name}");
        }

        // The triangles as placed match P4's count, and the placed bounds
        // match P4's corner-method bounds (every fixture is axis-aligned).
        let mut placed_triangles = 0;
        let mut placed_bounds: Option<BoundsMm> = None;
        for item in &geometry.build_items {
            let object = geometry
                .objects
                .iter()
                .find(|object| object.object_key == item.object_key)
                .unwrap();
            placed_triangles += object.triangle_count;
            let mesh = revision.mesh(item.object_key).unwrap();
            let bounds = transformed_bounds(&item.transform, &mesh.positions).unwrap();
            placed_bounds = Some(match placed_bounds {
                None => bounds,
                Some(mut union) => {
                    for axis in 0..3 {
                        union.min[axis] = union.min[axis].min(bounds.min[axis]);
                        union.max[axis] = union.max[axis].max(bounds.max[axis]);
                    }
                    union
                }
            });
        }
        let (triangles, bounds) = match &inspection {
            Inspection::Stl(stl) => (stl.triangle_count, stl.bounds_mm),
            Inspection::ThreeMf(model) => {
                assert_eq!(geometry.build_items.len(), model.build_item_count as usize);
                assert!(geometry.objects.len() <= model.object_count as usize);
                (model.triangle_count, model.bounds_mm)
            }
            Inspection::Gcode(_) => unreachable!("only STL and 3MF are listed"),
        };
        assert_eq!(placed_triangles, triangles, "{name}");
        assert_bounds_near(&placed_bounds.unwrap(), &bounds, 1e-4, name);
        loaded.push((name.clone(), revision));
    }

    let loaded_names: Vec<&str> = loaded.iter().map(|(name, _)| name.as_str()).collect();
    assert_eq!(
        loaded_names,
        [
            "core-two-objects.3mf",
            "cube-ascii-bare-solid.stl",
            "cube-ascii.stl",
            "cube-binary-solid-header.stl",
            "cube-binary.stl",
            "cube-for-slicers.stl",
            "orca-two-plates.3mf",
            "prusa-project.3mf",
        ]
    );
    for (name, revision) in &loaded {
        let geometry = revision.geometry();
        let summary: Vec<(u32, Option<&str>, usize, u64)> = geometry
            .objects
            .iter()
            .map(|object| {
                (
                    object.object_key,
                    object.name.as_deref(),
                    revision.mesh(object.object_key).unwrap().positions.len(),
                    object.triangle_count,
                )
            })
            .collect();
        let items: Vec<(u32, Option<u32>, bool)> = geometry
            .build_items
            .iter()
            .map(|item| (item.object_key, item.plate_index, item.printable))
            .collect();
        match name.as_str() {
            // Welded STL cubes: 8 vertices, 12 triangles, one object.
            stl if stl.ends_with(".stl") => {
                assert_eq!(summary, [(1, None, 8, 12)], "{name}");
                assert_eq!(items, [(1, None, true)], "{name}");
                let faces = &geometry.objects[0].lay_flat_faces;
                assert_eq!(faces.len(), 6, "{name}");
                assert!(faces
                    .iter()
                    .all(|face| (face.area_mm2 - 100.0).abs() < 1e-9));
            }
            "core-two-objects.3mf" => {
                assert_eq!(
                    summary,
                    [(1, Some("Cube A"), 8, 12), (2, Some("Cube B"), 8, 12)]
                );
                assert_eq!(items, [(1, None, true), (2, None, true)]);
                // Object 2's component is flattened into its frame.
                assert_eq!(geometry.objects[1].bounds_mm.min, [20.0, 0.0, 0.0]);
            }
            "orca-two-plates.3mf" => {
                assert_eq!(
                    summary,
                    [
                        (2, Some("cube-for-slicers.stl"), 8, 12),
                        (4, Some("cube-for-slicers.stl"), 8, 12)
                    ]
                );
                assert_eq!(items, [(2, Some(1), true), (4, Some(2), true)]);
                assert_eq!(geometry.build_items[1].transform[9..], [425.0, 119.0, 5.0]);
            }
            "prusa-project.3mf" => {
                assert_eq!(summary, [(1, None, 8, 12)]);
                assert_eq!(items, [(1, None, true)]);
            }
            other => panic!("unexpected fixture {other}"),
        }
    }
}

